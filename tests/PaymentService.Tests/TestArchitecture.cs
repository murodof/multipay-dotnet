{
    public static string RepositoryRoot
    {
        get
        {
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "MultiPay.sln")))
            {
                directory = directory.Parent;
            }
            return directory!.FullName;
        }
    }

    public static string SourceRoot => Path.Combine(RepositoryRoot, "src", "PaymentService");

    private static readonly Assembly Service = typeof(Program).Assembly;

    private static IEnumerable<string> SourceFiles(string relative = "", string pattern = "*.cs") =>
        Directory.EnumerateFiles(Path.Combine(SourceRoot, relative), pattern, SearchOption.AllDirectories)
            .Where(path =>
            {
                var local = Path.GetRelativePath(SourceRoot, path).Replace('\\', '/');
                return !local.StartsWith("bin/", StringComparison.Ordinal)
                    && !local.StartsWith("obj/", StringComparison.Ordinal)
                    && !local.StartsWith("Migrations/", StringComparison.Ordinal);
            })
            .Order(StringComparer.Ordinal);

    private static string Local(string path) => Path.GetRelativePath(SourceRoot, path);

    // ─── house style ───

    // No comments and no XML docs in src/: the why lives in CLAUDE.md, where it is reviewed, instead
    // of beside the code, where it drifts. Migrations/ is generated by `dotnet ef` and exempt.
    [Fact]
    public void Src_has_no_comments_or_xml_docs()
    {
        var violations = new List<string>();
        foreach (var path in SourceFiles())
        {
            var root = CSharpSyntaxTree.ParseText(File.ReadAllText(path)).GetRoot();
            foreach (var trivia in root.DescendantTrivia(descendIntoTrivia: true))
            {
                if (trivia.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia
                    or SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia)
                {
                    violations.Add($"{Local(path)}:{trivia.GetLocation().GetLineSpan().StartLinePosition.Line + 1}");
                }
            }
        }
        foreach (var path in SourceFiles(pattern: "*.cshtml"))
        {
            var text = File.ReadAllText(path);
            if (text.Contains("@*", StringComparison.Ordinal) || text.Contains("<!--", StringComparison.Ordinal))
            {
                violations.Add(Local(path));
            }
        }

        Assert.True(violations.Count == 0, $"move the explanation to CLAUDE.md: {string.Join(", ", violations)}");
    }

    // Errors travel as ErrorResponse; a throw would escape the envelope and its HTTP status.
    [Fact]
    public void Services_repositories_and_utils_return_errors_instead_of_throwing()
    {
        var violations = new List<string>();
        foreach (var folder in new[] { "Infrastructure/Services", "Infrastructure/Repositories", "Infrastructure/Utils" })
        {
            foreach (var path in SourceFiles(folder))
            {
                var root = CSharpSyntaxTree.ParseText(File.ReadAllText(path)).GetRoot();
                violations.AddRange(root.DescendantNodes()
                    .Where(node => node is ThrowStatementSyntax or ThrowExpressionSyntax)
                    .Select(node => $"{Local(path)}:{node.GetLocation().GetLineSpan().StartLinePosition.Line + 1}"));
            }
        }

        Assert.True(violations.Count == 0, $"return ErrorResponse instead of throwing: {string.Join(", ", violations)}");
    }

    // Python reads `get_utc_now()` once per use case and the tests freeze it; here that is the
    // injected TimeProvider, so the wall clock is never read directly.
    [Fact]
    public void Time_comes_only_from_the_injected_clock()
    {
        var violations = SourceFiles()
            .SelectMany(path => File.ReadAllLines(path).Select((line, index) => (path, line, index)))
            .Where(item => WallClock().IsMatch(item.line))
            .Select(item => $"{Local(item.path)}:{item.index + 1}")
            .ToList();

        Assert.True(violations.Count == 0, $"use TimeProvider: {string.Join(", ", violations)}");
    }

    [GeneratedRegex(@"\b(DateTime|DateTimeOffset)\.(Now|UtcNow|Today)\b")]
    private static partial Regex WallClock();

    // ─── layers ───

    [Fact]
    public void Layers_only_depend_downwards()
    {
        var rules = new (string Layer, string[] Forbidden)[]
        {
            ("PaymentService.Domain", ["PaymentService.Api", "PaymentService.Infrastructure"]),
            ("PaymentService.Infrastructure", ["PaymentService.Api"]),
            ("PaymentService.Core", ["PaymentService.Api"]),
            ("PaymentService.Infrastructure.Utils", ["PaymentService.Infrastructure.Services", "PaymentService.Infrastructure.Repositories", "PaymentService.Infrastructure.ExternalServices"]),
            ("PaymentService.Infrastructure.Repositories", ["PaymentService.Infrastructure.Services", "PaymentService.Infrastructure.ExternalServices"]),
            ("PaymentService.Infrastructure.ExternalServices", ["PaymentService.Infrastructure.Services", "PaymentService.Infrastructure.Repositories"]),
        };
        foreach (var (layer, forbidden) in rules)
        {
            var result = Types.InAssembly(Service).That().ResideInNamespace(layer).ShouldNot().HaveDependencyOnAny(forbidden).GetResult();

            Assert.True(result.IsSuccessful, $"{layer} -> {string.Join(", ", result.FailingTypeNames ?? [])}");
        }
    }

    // Controllers are thin: they receive the service (and the guard through model binding), never a
    // repository, DbContext or client.
    [Fact]
    public void Controllers_take_services_not_repositories_or_clients()
    {
        var result = Types.InAssembly(Service).That().ResideInNamespace("PaymentService.Api")
            .ShouldNot().HaveDependencyOnAny("PaymentService.Infrastructure.Repositories", "PaymentService.Infrastructure.ExternalServices", "Microsoft.EntityFrameworkCore")
            .GetResult();

        Assert.True(result.IsSuccessful, string.Join(", ", result.FailingTypeNames ?? []));
    }

    // ─── DI convention ───

    // The replacement for Python's static inject(): every service, repository and client is
    // registered in the container, so nothing is constructed by hand inside a request.
    [Fact]
    public void Services_repositories_and_clients_are_registered()
    {
        var missing = new List<string>();
        using var scope = App.Services.CreateScope();
        foreach (var type in Service.GetTypes().Where(type =>
                     type is { IsClass: true, IsAbstract: false, IsPublic: true }
                     && type.Namespace is { } name && name.StartsWith("PaymentService.Infrastructure", StringComparison.Ordinal)
                     && !name.EndsWith(".Utils", StringComparison.Ordinal)
                     && (type.Name.EndsWith("Service", StringComparison.Ordinal) || type.Name.EndsWith("Repository", StringComparison.Ordinal) || type.Name.EndsWith("Client", StringComparison.Ordinal))))
        {
            if (scope.ServiceProvider.GetService(type) is null)
            {
                missing.Add(type.FullName!);
            }
        }

        Assert.True(missing.Count == 0, $"not registered: {string.Join(", ", missing)}");
    }

    [Fact]
    public void Redis_client_is_a_singleton_and_db_context_is_scoped()
