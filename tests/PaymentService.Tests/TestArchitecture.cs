// Executable versions of the conventions documented in CLAUDE.md, carried over from the Python
// service's tests/test_architecture.py and translated to .NET.
//
// Every rule here exists because breaking it fails *silently*. Prose in CLAUDE.md is advisory;
// these fail the build. When a rule is genuinely wrong for a new case, add it to the exemption set
// *with a reason* rather than deleting the rule.
[Collection("app")]
