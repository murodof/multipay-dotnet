    [Fact]
    public void The_migration_snapshot_has_one_head()
    {
        var snapshots = Service.GetTypes().Where(type => type.IsSubclassOf(typeof(Microsoft.EntityFrameworkCore.Infrastructure.ModelSnapshot))).ToList();
        var migrations = Service.GetTypes().Where(type => type.IsSubclassOf(typeof(Migration))).ToList();

        Assert.Single(snapshots);
        Assert.Equal(migrations.Count, migrations.Select(type => type.GetCustomAttribute<MigrationAttribute>()!.Id).Distinct().Count());
    }

    // The sliding-window and compare-and-set scripts are the same Lua as the Python service's,
    // modulo indentation.
    [Fact]
    public void Lua_scripts_are_unchanged_from_python()
    {
        var python = JsonNode.Parse(File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Fixtures", "python_lua_scripts.json")))!.AsObject();
        var source = File.ReadAllText(Path.Combine(SourceRoot, "Infrastructure", "ExternalServices", "RedisClient.cs"));
        var scripts = Regex.Matches(source, "const string (\\w+) = \"\"\"(.*?)\"\"\";", RegexOptions.Singleline)
            .ToDictionary(match => match.Groups[1].Value, match => Normalize(match.Groups[2].Value));

        Assert.Equal(Normalize(python["sliding_window"]!.GetValue<string>()), scripts["SlidingWindow"]);
        Assert.Equal(Normalize(python["compare_set"]!.GetValue<string>()), scripts["CompareSet"]);
        Assert.Equal(Normalize(python["compare_delete"]!.GetValue<string>()), scripts["CompareDelete"]);
    }

    private static string Normalize(string script) =>
        string.Join("\n", script.Split('\n').Select(line => line.Trim()).Where(line => line.Length > 0));
