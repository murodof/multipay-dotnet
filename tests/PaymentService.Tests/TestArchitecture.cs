    // ─── response envelope and routes ───

    private static IEnumerable<MethodInfo> Actions() =>
        Service.GetTypes()
            .Where(type => typeof(ControllerBase).IsAssignableFrom(type) && !type.IsAbstract)
            .SelectMany(type => type.GetMethods(BindingFlags.Public | BindingFlags.Instance))
            .Where(method => method.GetCustomAttributes<Microsoft.AspNetCore.Mvc.Routing.HttpMethodAttribute>().Any());

    [Fact]
    public void Routes_declare_the_response_envelope()
    {
        var missing = Actions().Where(method => method.ReturnType != typeof(Task<BaseResponse>)).Select(method => method.Name).ToList();

        Assert.True(missing.Count == 0, $"actions not returning Task<BaseResponse>: {string.Join(", ", missing)}");
    }

    private static readonly HashSet<string> PUBLIC_ROUTES = ["CreateUzcardSession", "CreateHumoSession", "GetReceipt"];

    // A new route must either sit behind the session guard or be listed here, so nothing becomes
    // public by omission.
    [Fact]
    public void Every_route_is_public_or_uses_the_session_guard()
    {
        var unlisted = Actions()
            .Where(method => !PUBLIC_ROUTES.Contains(method.Name))
            .Where(method => !method.GetParameters().Any(parameter =>
                parameter.ParameterType == typeof(SessionAccess)
                && parameter.GetCustomAttribute<ModelBinderAttribute>()?.BinderType == typeof(SessionAccessBinder)))
            .Select(method => $"{method.DeclaringType!.Name}.{method.Name}")
            .ToList();

        Assert.True(unlisted.Count == 0, $"routes neither guarded nor public: {string.Join(", ", unlisted)}");
    }

    [Fact]
    public void Every_guarded_controller_names_its_provider()
    {
        var controllers = Service.GetTypes().Where(type => type.IsSubclassOf(typeof(Api.Controllers.ProviderController)));

        Assert.All(controllers, controller => Assert.NotNull(controller.GetCustomAttribute<ProviderAttribute>()));
    }

    [Fact]
    public void Status_codes_are_unique_negative_and_translated()
    {
        var values = StatusCodes.All.Select(member => member.Value).ToList();

        Assert.Equal(35, values.Count);
        Assert.Equal(values.Count, values.Distinct().Count());
        foreach (var member in StatusCodes.All)
        {
            Assert.InRange(member.Value, -2999, -2000);
            Assert.InRange(member.HttpStatus, 400, 599);
            Assert.Equal(["uz", "en", "ru"], member.Message.Keys);
            Assert.All(member.Message.Values, message => Assert.NotEmpty(message));
        }
        Assert.Equal(
            typeof(StatusCodes).GetFields(BindingFlags.Public | BindingFlags.Static).Where(field => field.FieldType == typeof(StatusCodes)).Select(field => field.Name),
            StatusCodes.All.Select(member => member.Name));
    }

